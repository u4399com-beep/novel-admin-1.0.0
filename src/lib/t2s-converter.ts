const TRAD_SET = new Set<string>();
for (const [k, v] of T2S_MAP) { if (k !== v) TRAD_SET.add(k); }

// ==================== 公开 API ====================

export function convertTraditionalToSimplified(text: string): string {
  if (!text) return text;
  // Step 1: 逐字替换（繁→简）
  let r = '';
  for (const ch of text) {
    const cp = ch.codePointAt(0) ?? 0;
    if ((cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf)) {
      r += T2S_MAP.get(ch) ?? ch;
    } else {
      r += ch;
    }
  }
  // Step 2: 整词替换（长词优先，在已半简化的文本上匹配）
  for (const [t, s] of T2S_WORDS) { r = r.split(t).join(s); }
  return r;
}

export function isProbablyTraditional(text: string): boolean {
  if (!text || text.length < 4) return false;
  let cjk = 0, trad = 0;
  for (let i = 0, n = Math.min(text.length, 500); i < n; i++) {
    const cp = text[i].codePointAt(0) ?? 0;
    if ((cp >= 0x4e00 && cp <= 0x9fff) || (cp >= 0x3400 && cp <= 0x4dbf)) {
      cjk++;
      if (TRAD_SET.has(text[i])) trad++;
    }
  }
  return cjk > 0 && (trad / cjk) > 0.03;
}
